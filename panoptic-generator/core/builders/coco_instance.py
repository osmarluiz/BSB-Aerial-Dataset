"""COCO Instance Segmentation format builder."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from core.builders import register_builder
from core.models import (
    AnnotationFormat,
    CategoryInfo,
    FileOutput,
    SegmentInfo,
    TileLocation,
)


@register_builder(AnnotationFormat.COCO_INSTANCE)
class COCOInstanceBuilder:
    """Accumulates instance annotation data tile-by-tile, then produces COCO JSON."""

    def __init__(self) -> None:
        self._images: dict[str, list[dict]] = defaultdict(list)
        self._annotations: dict[str, list[dict]] = defaultdict(list)
        self._ann_id: int = 1  # Globally unique annotation ID

    def add_tile(
        self, location: TileLocation, segments: list[SegmentInfo]
    ) -> None:
        split = location.split

        self._images[split].append(
            {
                "id": location.id,
                "file_name": f"{location.id}.tiff",
                "width": location.width,
                "height": location.height,
            }
        )

        for seg in segments:
            # Instance format only includes things with contours
            if seg.contour is None:
                continue

            self._annotations[split].append(
                {
                    "id": self._ann_id,
                    "image_id": location.id,
                    "category_id": seg.category_id,
                    "segmentation": seg.contour,
                    "bbox": list(seg.bbox),
                    "area": seg.area,
                    "iscrowd": 0,
                }
            )
            self._ann_id += 1

    def finalize(self, categories: list[CategoryInfo]) -> list[FileOutput]:
        # Only thing categories
        cat_list = [
            {
                "id": c.id,
                "name": c.name,
                "supercategory": c.supercategory,
            }
            for c in categories
            if c.is_thing
        ]

        outputs = []
        for split in self._images:
            data = {
                "info": {
                    "description": "Generated by Panoptic Generator v2",
                    "version": "2.0",
                },
                "licenses": [{"id": 0, "name": "Unknown"}],
                "images": self._images[split],
                "annotations": self._annotations.get(split, []),
                "categories": cat_list,
            }
            outputs.append(
                FileOutput(
                    relative_path=Path(f"annotations/instance_{split}.json"),
                    content=json.dumps(data, indent=2),
                )
            )

        return outputs
