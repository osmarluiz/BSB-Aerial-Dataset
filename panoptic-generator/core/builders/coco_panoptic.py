"""COCO Panoptic format builder."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from core.builders import register_builder
from core.models import (
    AnnotationFormat,
    CategoryInfo,
    FileOutput,
    SegmentInfo,
    TileLocation,
)
from core.utils import encode_panoptic_id


@register_builder(AnnotationFormat.COCO_PANOPTIC)
class COCOPanopticBuilder:
    """Accumulates panoptic annotation data tile-by-tile, then produces COCO JSON."""

    def __init__(self) -> None:
        self._images: dict[str, list[dict]] = defaultdict(list)
        self._annotations: dict[str, list[dict]] = defaultdict(list)

    def add_tile(
        self, location: TileLocation, segments: list[SegmentInfo]
    ) -> None:
        split = location.split

        self._images[split].append(
            {
                "id": location.id,
                "file_name": f"{location.id}.tiff",
                "width": location.width,
                "height": location.height,
            }
        )

        segments_info = []
        for seg in segments:
            r, g, b = encode_panoptic_id(seg.instance_id)
            rgb_id = r + g * 256 + b * 65536
            segments_info.append(
                {
                    "id": rgb_id,
                    "category_id": seg.category_id,
                    "iscrowd": 0,
                    "bbox": list(seg.bbox),
                    "area": seg.area,
                }
            )

        self._annotations[split].append(
            {
                "image_id": location.id,
                "file_name": f"{location.id}.png",
                "segments_info": segments_info,
            }
        )

    def finalize(self, categories: list[CategoryInfo]) -> list[FileOutput]:
        cat_list = [
            {
                "id": c.id,
                "name": c.name,
                "isthing": int(c.is_thing),
                "supercategory": c.supercategory,
            }
            for c in categories
        ]

        outputs = []
        for split in self._images:
            data = {
                "info": {
                    "description": "Generated by Panoptic Generator v2",
                    "version": "2.0",
                },
                "licenses": [{"id": 0, "name": "Unknown"}],
                "images": self._images[split],
                "annotations": self._annotations[split],
                "categories": cat_list,
            }
            outputs.append(
                FileOutput(
                    relative_path=Path(f"annotations/panoptic_{split}.json"),
                    content=json.dumps(data, indent=2),
                )
            )

        return outputs
